/* ============================================================
   scanf_addr.c —— scanf 为什么用 %d 而不是 %p

   你的疑问：「地址不是应该用 %p 吗？」

   这题的四个选项，我把它们都跑一遍，看哪个对、哪个错。
   ============================================================ */
#include <stdio.h>
#include "utf8_console.h"

int main(void)
{
    enable_utf8_console();

    int a = 0;
    int *p = &a;

    printf("############################################################\n");
    printf("#   scanf 要的是地址 —— 四个选项逐个试                      #\n");
    printf("############################################################\n\n");

    printf("前提：int a = 0;  int *p = &a;\n");
    printf("      a 的地址 = %p\n", (void *)&a);
    printf("      p 里存的 = %p   （和 &a 一样）\n", (void *)p);
    printf("      *p 的值  = %d   （就是 a 的值）\n\n", *p);

    /* ---------- 先把 printf 和 scanf 的分工讲清 ---------- */
    printf("============================================================\n");
    printf("先搞清一件事：printf 和 scanf 里 %%d 的意思【不一样】\n");
    printf("============================================================\n\n");
    printf("  printf(\"%%d\", x)      -> 把一个 int 的值【打印出来】\n");
    printf("  printf(\"%%p\", p)      -> 把一个地址【打印成地址格式】\n\n");
    printf("  scanf(\"%%d\", &x)      -> 从键盘读一个 int，【写进】这个地址\n");
    printf("  scanf(\"%%p\", &p)      -> 从键盘读一个地址\n\n");
    printf("  关键：scanf 里 %%d 描述的是【要读进来的东西是什么类型】\n");
    printf("        它是 int，所以写 %%d —— 跟「传了个地址」没关系\n\n");
    printf("  ⚠️ printf 的第二个参数是【要给出去的值】\n");
    printf("     scanf  的第二个参数是【要写进去的地址】—— 分工不同\n\n");

    /* ---------- 四个选项 ---------- */
    printf("============================================================\n");
    printf("四个选项逐个分析\n");
    printf("============================================================\n\n");

    /* --- 选项 A --- */
    printf("--- A: scanf(\"%%d\", a);  ---\n");
    printf("  传的是 a 的【值】= %d，不是地址\n", a);
    printf("  scanf 会把这个数字当成地址去写 -> 往地址 0 写 -> 崩溃\n");
    printf("  ❌ 错（把「值」当地址用了）\n\n");

    /* --- 选项 B --- */
    printf("--- B: scanf(\"%%d\", &a);  和  scanf(\"%%d\", p);  ---\n");
    printf("  &a = %p   （a 的地址）\n", (void *)&a);
    printf("  p  = %p   （p 里存的也是 a 的地址）\n", (void *)p);
    printf("  两者完全相同 -> %s\n", (&a == p) ? "所以两种写法等价" : "居然不同?");
    printf("  ✅ 对（这就是答案）\n\n");
    {
        /* 真的验证一下：用 p 来写，看 a 变不变 */
        int t = 0;
        int *tp = &t;
        printf("  实测验证：\n");
        printf("      int t = 0;  int *tp = &t;\n");
        printf("      假设 scanf(\"%%d\", tp) 读到了 86 —— 我们直接模拟：\n");
        *tp = 86;                       /* 等价于 scanf 往 tp 指向的格子写 86 */
        printf("      写完之后 t = %d   <- 通过指针写成功了\n", t);
        printf("      说明 \"%%d\" + 指针 确实能写进那个 int 格子\n\n");
    }

    /* --- 选项 C --- */
    printf("--- C: scanf(\"%%d\", &p);  ---\n");
    printf("  &p = %p   （这是【指针变量 p 自己的地址】）\n", (void *)&p);
    printf("  它的类型是 int **，而 %%d 要的是 int *\n");
    printf("  -> 类型不匹配，会把一个整数写到 p 这个格子（8 字节）里\n");
    printf("  -> 结果是 p 里存的地址被改坏，之后再用 p 就完蛋\n");
    printf("  ❌ 错（传的是「指针自己的地址」，多了一层）\n\n");

    /* --- 选项 D --- */
    printf("--- D: scanf(\"%%d\", *p);  ---\n");
    printf("  *p 的值 = %d   （这是 a 目前的【值】，不是地址）\n", *p);
    printf("  和选项 A 一样的问题：把值当地址用\n");
    printf("  ❌ 错（*p 是「进门拿东西」，拿到的是值）\n\n");

    /* ---------- 总结 ---------- */
    printf("============================================================\n");
    printf("为什么你的直觉（用 %%p）是错的\n");
    printf("============================================================\n\n");
    printf("  你的推理大概是：\n");
    printf("     「scanf 第二个参数要传地址」 -> \"地址就该用 %%p\"\n\n");
    printf("  但 %%p 的含义是【我要读/写的东西本身是一个地址】，\n");
    printf("  而这题要读进来的是一个【整数】，要写进一个【int 格子】。\n\n");
    printf("  打个比方：\n");
    printf("     %%d  = 「我要寄一个【整数包裹】」\n");
    printf("     &a  = 「寄到这个【门牌号】」\n");
    printf("     格式符说的是【包裹是什么】，地址说的是【送到哪】\n");
    printf("     两件事，别混\n\n");
    printf("  反过来看就懂了：如果真要读一个地址，才写 %%p\n");
    printf("     scanf(\"%%p\", &p);   <- 这才是 %%p 的用法\n\n");

    printf("============================================================\n");
    printf("对照表（建议背下来）\n");
    printf("============================================================\n\n");
    printf("  想做什么                      printf            scanf\n");
    printf("  ----------------------------  ----------------  ------------------\n");
    printf("  打印/读入一个 int 值          printf(\"%%d\", a)   scanf(\"%%d\", &a)\n");
    printf("  打印/读入一个地址             printf(\"%%p\", p)   scanf(\"%%p\", &p)\n");
    printf("  用指针读入到它指向的格子       --               scanf(\"%%d\", p)\n\n");
    printf("  ★ 记这一条就够：\n");
    printf("     printf 收【值】，scanf 收【地址】\n");
    printf("     而格式符（%%d / %%p）描述的是【数据本身是什么类型】\n");
    printf("     —— 跟 「传值还是传地址」 是两件独立的事\n");

    return 0;
}
