/* ============================================================
   func_output.c —— 指针作"输出参数"（教材 7.4）
   解决一个实际问题：C 的函数只能 return 一个值，
                    但用指针就能"带回"多个结果
   ============================================================ */
#include <stdio.h>
#include "utf8_console.h"

/* ============================================================
   1. 经典例子：swap —— 最基础的"输出参数"
   ============================================================ */
void swap(int *x, int *y)
{
    int t = *x;
    *x = *y;
    *y = t;
}

/* ============================================================
   2. 一个函数带回两个结果：同时求最大最小
   ⚠️ 如果不用指针，这个函数做不到 —— return 只能带一个值
   ============================================================ */
void max_and_min(int arr[], int n, int *out_max, int *out_min)
{
    int i;
    *out_max = arr[0];       /* 通过指针写回调用者的变量 */
    *out_min = arr[0];
    for (i = 1; i < n; i++) {
        if (arr[i] > *out_max) *out_max = arr[i];
        if (arr[i] < *out_min) *out_min = arr[i];
    }
}

/* ============================================================
   3. 带回三个结果：求和、平均、计数
   ============================================================ */
int stats(int arr[], int n, double *out_avg)
{
    int i, total = 0;
    for (i = 0; i < n; i++) {
        total += arr[i];
    }
    *out_avg = (n > 0) ? (double)total / n : 0.0;   /* 写回平均值 */
    return total;                                    /* 用 return 带求和 */
}

/* ============================================================
   4. 除法：用指针带回"是否成功"
   这样调用者就不会拿到一个没意义的商
   ============================================================ */
int safe_divide(double a, double b, double *out_result)
{
    if (b == 0.0) {
        return 0;            /* 失败：0 表示除数为零 */
    }
    *out_result = a / b;
    return 1;                /* 成功 */
}

/* ============================================================
   ⚠️ 常见错误：以为在函数里改指针本身能影响到外面
   ============================================================ */
void wrong_pointer(int *p)
{
    static int dummy = 999;
    p = &dummy;              /* ❌ 只改了"复印件"p 自己，外面的指针没变 */
}

/* ============================================================
   ✅ 正确做法：要改指针本身，得传"指针的地址"（二级指针）
   ============================================================ */
void right_pointer(int **p, int *target)
{
    *p = target;             /* ✅ 通过二级指针, 真的改到了外面的指针 */
}

int main(void)
{
    enable_utf8_console();

    printf("========== 1. swap: 最基础的输出参数 ==========\n");
    {
        int a = 3, b = 5;
        printf("交换前: a = %d, b = %d\n", a, b);
        swap(&a, &b);        /* 传的是地址 */
        printf("交换后: a = %d, b = %d\n", a, b);
        printf("=> 传 &a &b, 函数里用 *x *y 就能改到外面\n");
    }

    printf("\n========== 2. 一个函数带回两个结果 ==========\n");
    {
        int data[6] = {23, 7, 91, 45, 12, 68};
        int mx, mn;
        int i;
        printf("数组: [");
        for (i = 0; i < 6; i++) printf("%d%s", data[i], i < 5 ? ", " : "");
        printf("]\n");
        max_and_min(data, 6, &mx, &mn);
        printf("最大值 = %d   最小值 = %d\n", mx, mn);
        printf("=> 一次调用带回两个结果! 只用 return 做不到这个\n");
    }

    printf("\n========== 3. 带回三个结果 ==========\n");
    {
        int data[5] = {80, 92, 75, 88, 95};
        double avg = 0.0;
        int total = stats(data, 5, &avg);      /* return 带求和, 指针带平均 */
        printf("求和 = %d   平均 = %.2f   个数 = 5\n", total, avg);
        printf("=> return 带一个, 指针带其余的 —— 这是 C 的常用手法\n");
    }

    printf("\n========== 4. 用指针带回\"成功与否\" ==========\n");
    {
        double result;
        if (safe_divide(10.0, 4.0, &result)) {
            printf("10 / 4 = %.2f   (成功)\n", result);
        }
        if (!safe_divide(10.0, 0.0, &result)) {
            printf("10 / 0 -> 失败: 除数为零 (result 没被赋值, 我们也没去读它)\n");
        }
        printf("=> 用返回值报错, 用指针带结果, 比直接崩掉好得多\n");
    }

    printf("\n========== 5. ⚠️ 陷阱: 改指针本身 ==========\n");
    {
        int x = 1, y = 2;
        int *p = &x;

        printf("初始: *p = %d  (p 指向 x)\n", *p);

        wrong_pointer(p);
        printf("wrong_pointer(p) 之后: *p = %d  <-- 没变!\n", *p);
        printf("  原因: 形参 p 是实参的复印件, 改复印件不影响原件\n");

        right_pointer(&p, &y);
        printf("right_pointer(&p, &y) 之后: *p = %d  <-- 变了!\n", *p);
        printf("  原因: 传的是指针的地址, 用 **p 就能改到外面的指针\n");
    }

    printf("\n========== 6. 总结: 什么时候要传地址 ==========\n");
    printf("想让函数【改到外面的东西】, 就传它的地址:\n");
    printf("  想让函数改 int      -> 传 int *      -> 函数里用 *p = ...\n");
    printf("  想让函数改 int *    -> 传 int **     -> 函数里用 **p = ...\n");
    printf("  想让函数改整个数组  -> 传数组名(即地址) -> 函数里用 p[i] = ...\n");
    printf("只想读不想改 -> 直接传值就行 (如 void print(int n))\n");

    return 0;
}
