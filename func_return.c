/* ============================================================
   func_return.c —— 返回指针的函数 + 野指针陷阱（教材 7.4）
   ⚠️ 本程序里有一段"故意写错"的代码，用来演示危险后果。
      错误那部分被注释掉了，想亲眼看后果可以取消注释。
   ============================================================ */
#include <stdio.h>
#include "utf8_console.h"

/* ============================================================
   ❌ 错误示范：返回局部数组的地址

   ⚠️ 注意：编译这个文件时 gcc 会给出警告 ——
        warning: function returns address of local variable
      这个警告是【故意保留】的！它正好说明：
      编译器能发现这类错误，所以以后看到这个警告千万别忽略。
      （用 -Wall 编译就是为了让这类警告显示出来）
   ============================================================ */
int *get_array_by_value(void)
{
    int arr[3] = {1, 2, 3};
    printf("  [函数内] 局部数组 arr 的地址 = %p\n", (void *)arr);
    return arr;          /* ⚠️ 危险！arr 在函数返回后就被销毁了 */
}

/* ============================================================
   ✅ 正确做法 1：用 static，让数组活到程序结束
   ============================================================ */
int *get_array_static(void)
{
    static int arr[3] = {1, 2, 3};   /* static: 放在全局区, 不会随函数结束消失 */
    printf("  [函数内] static 数组地址   = %p\n", (void *)arr);
    return arr;
}

/* ============================================================
   ✅ 正确做法 2：调用者提供数组（推荐！最常用）
   把结果写进调用者给的数组里，这样谁负责内存很清楚
   ============================================================ */
void fill_array(int *out, int n)
{
    int i;
    for (i = 0; i < n; i++) {
        out[i] = (i + 1) * 10;      /* 写进调用者的数组 */
    }
}

/* ============================================================
   ✅ 正确做法 3：返回指向"静态字符串"的指针（只读，安全）
   字符串字面量存放在只读数据区，程序运行期间一直有效
   ============================================================ */
const char *get_name(void)
{
    return "pointer";        /* 这不是局部变量，是常量区的字面量 */
}

/* ============================================================
   补充：返回局部变量的"值"是安全的！
   ============================================================ */
int get_number(void)
{
    int x = 42;
    return x;                /* ✅ 返回的是值的拷贝，完全没问题 */
}

int main(void)
{
    enable_utf8_console();
    int *p;
    int buf[5];

    printf("========== 1. 为什么不能返回局部数组的地址 ==========\n");
    printf("函数里的局部变量放在【栈】上，函数一返回，\n");
    printf("它占的那块内存就被回收了（会被别的函数覆盖）。\n");
    printf("这时你手里的指针还指着那块地方 —— 这就是【野指针 / 悬空指针】。\n\n");

    printf("看看错误函数的地址（不真用它，只打印）:\n");
    {
        int *bad = get_array_by_value();
        printf("  [函数外] 拿到的地址         = %p  <-- 和上面一样, 但那块地已经没了\n",
               (void *)bad);
        printf("  => 这块内存随时可能被覆盖, 读出来的数不可信, 写进去更危险\n");
    }

    printf("\n========== 2. ✅ 正确做法 1: static ==========\n");
    p = get_array_static();
    printf("  [函数外] 拿到的地址         = %p\n", (void *)p);
    printf("  读出内容: p[0]=%d p[1]=%d p[2]=%d\n", p[0], p[1], p[2]);
    printf("  => 内容是对的, 因为 static 数组不随函数结束销毁\n");
    printf("  ⚠️ 但注意: 全程序只有一份, 下次再调用会覆盖上次的结果\n");

    printf("\n========== 3. ✅ 正确做法 2: 调用者提供数组（推荐） ==========\n");
    fill_array(buf, 5);
    printf("  buf = [%d, %d, %d, %d, %d]\n", buf[0], buf[1], buf[2], buf[3], buf[4]);
    printf("  => 内存由调用者（main）提供, 谁负责释放很清楚, 最不容易出错\n");

    printf("\n========== 4. ✅ 正确做法 3: 返回静态字符串（只读） ==========\n");
    printf("  get_name() = %s\n", get_name());
    printf("  => 字符串字面量在只读区, 一直有效; 但只能读, 不能改\n");

    printf("\n========== 5. 对比: 返回局部变量的【值】是安全的 ==========\n");
    {
        int v = get_number();
        printf("  get_number() = %d   <-- 完全没问题\n", v);
    }
    printf("  => 返回【值】= 拷贝一份带走; 返回【地址】= 把门牌号给你, 但房子拆了\n");
    printf("     这是关键区别！\n");

    printf("\n========== 6. 一句话总结 ==========\n");
    printf("  不要返回局部变量的地址（栈上的东西出了函数就没了）\n");
    printf("  要返回地址, 就用 static / 让调用者提供数组 / 用 malloc\n");

    return 0;
}
