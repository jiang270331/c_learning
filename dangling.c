/* ============================================================
   dangling.c —— 为什么不能返回局部变量的地址（悬空指针）

   你在练习网站答对了这题，现在把这个"为什么"讲透。

   核心：局部变量住在【栈】上。函数一返回，那块地就被收回。
        你手里的地址还指着那儿 —— 这叫【悬空指针 / 野指针】。
        之后那块地会被别的函数覆盖，你读到的就是别人的数据。

   本程序做四件事：
     1. 看地址：局部变量在栈（0x62xxxx），static 在全局区（0x40xxxx）
     2. 抓现行：调一次别的函数，把刚才那块地覆盖掉，看数据怎么变的
     3. 看警告：编译器其实早就警告你了
     4. 列对法：三种安全做法 + 一张对照表
   ============================================================ */
#include <stdio.h>
#include "utf8_console.h"

/* ============================================================
   ❌ 错误：返回局部变量的地址
   ============================================================ */
int *bad_return(void)
{
    int local = 111;          /* 住在栈上，函数返回后就没了 */
    printf("  [bad_return 内部] local 的地址 = %p\n", (void *)&local);
    return &local;            /* ⚠️ 把这个地址给出去了 */
}

/* ============================================================
   一个"捣乱"用的函数：它会占用栈，把刚才那块地覆盖
   ============================================================ */
int mess_up_stack(void)
{
    int junk[4];
    int i;
    junk[0] = 8888;
    junk[1] = 7777;
    junk[2] = 6666;
    junk[3] = 5555;
    for (i = 0; i < 4; i++) {
        printf("  [mess_up 内部] junk[%d] 地址 = %p  值 = %d\n",
               i, (void *)&junk[i], junk[i]);
    }
    return junk[0] + junk[1] + junk[2] + junk[3];
}

/* ============================================================
   ✅ 对法一：static —— 放进全局区，活到程序结束
   ============================================================ */
int *good_static(void)
{
    static int v = 222;
    printf("  [good_static 内部] v 的地址 = %p  （全局区）\n", (void *)&v);
    return &v;
}

/* ============================================================
   ✅ 对法二：调用者提供地址（推荐）
   ============================================================ */
void good_fill(int *out)
{
    *out = 333;               /* 写进调用者给的格子 */
}

/* ============================================================
   ✅ 对法三：返回静态字符串（只读，安全）
   ============================================================ */
const char *good_name(void)
{
    return "pointer";         /* 字面量在只读区，一直有效 */
}

int main(void)
{
    enable_utf8_console();

    printf("############################################################\n");
    printf("#  为什么不能返回局部变量的地址                              #\n");
    printf("############################################################\n\n");

    /* ---------- 1. 先看地址：栈 vs 全局区 ---------- */
    printf("============================================================\n");
    printf("1. 先看地址：局部变量在【栈】，static 在【全局区】\n");
    printf("============================================================\n\n");
    {
        int stack_var = 1;
        static int static_var = 2;
        printf("  局部变量 stack_var 的地址 = %p   <- 0x62 开头 = 栈\n",
               (void *)&stack_var);
        printf("  static  static_var 的地址 = %p   <- 0x40 开头 = 全局区\n",
               (void *)&static_var);
        printf("\n  栈区：函数返回就回收     全局区：程序结束才回收\n");
        printf("  所以只有前者不能把地址给出去\n");
    }

    /* ---------- 2. 抓现行：覆盖那块内存 ---------- */
    printf("\n============================================================\n");
    printf("2. 抓现行：函数返回后，那块地真的会被覆盖\n");
    printf("============================================================\n\n");
    {
        int *p = bad_return();
        printf("  [main 里] 拿到的地址 = %p\n", (void *)p);
        printf("  [main 里] 立刻读一次 *p = %d\n", *p);
        printf("           ⚠️ 本来应该是 111，但实测常常已经不是了 ——\n");
        printf("              因为 bad_return 返回后、这次 printf 执行前，\n");
        printf("              中间的函数调用就已经把那块栈覆盖了。\n");
        printf("              栈的回收是【立刻】发生的，没有缓冲期。\n");
        printf("\n  现在调用一个普通函数 mess_up_stack()，它会用到栈：\n\n");
        mess_up_stack();
        printf("\n  [main 里] 覆盖之后再读同一个地址 *p = %d\n", *p);
        printf("  ⚠️ 值变了！那块地已经不属于你了\n");
        printf("  => 这就是【悬空指针】：地址还在，但房子已经拆了\n");
        printf("     读它得到的是垃圾（甚至是别人的数据），写它更危险\n");
    }

    /* ---------- 3. 编译器其实早警告你了 ---------- */
    printf("\n============================================================\n");
    printf("3. 编译器其实早就警告你了\n");
    printf("============================================================\n\n");
    printf("  编译这个文件（加了 -Wall）时会看到：\n\n");
    printf("      warning: function returns address of local variable\n\n");
    printf("  这个警告是【故意保留】的 —— 它在告诉你：这里有 bug。\n");
    printf("  => 以后看到这个警告，千万别忽略。\n");
    printf("     （编译时加 -Wall 就是为了让它显示出来）\n");

    /* ---------- 4. 三种安全做法 ---------- */
    printf("\n============================================================\n");
    printf("4. 要返回地址，用这三种做法\n");
    printf("============================================================\n\n");

    printf("  对法一：static —— 放进全局区，全程有效\n");
    {
        int *p = good_static();
        printf("      [main] 拿到 %p，读出 *p = %d  ✅\n", (void *)p, *p);
        printf("      ⚠️ 副作用：全程序只有一份，再调用会覆盖上次的值\n");
    }

    printf("\n  对法二：调用者提供地址（⭐ 推荐）\n");
    {
        int mine = 0;
        good_fill(&mine);
        printf("      [main] 自己的变量 mine = %d  ✅\n", mine);
        printf("      内存由调用者提供，谁负责、活多久都很清楚\n");
    }

    printf("\n  对法三：返回静态字符串（只读）\n");
    {
        const char *s = good_name();
        printf("      [main] 拿到 \"%s\"  ✅（只读区，一直有效）\n", s);
        printf("      但只能读，不能改 —— 改了会崩\n");
    }

    printf("\n  还有第四种：malloc（第 8 章会学）\n");
    printf("      int *p = malloc(sizeof(int));\n");
    printf("      -> 内存在【堆】上，不随函数返回释放，直到你 free 它\n");
    printf("      -> 代价：必须记得 free，否则内存泄漏\n");

    /* ---------- 5. 对照表 ---------- */
    printf("\n############################################################\n");
    printf("#  五种返回方式对照                                         #\n");
    printf("############################################################\n\n");
    printf("  做法                        地址在哪    函数返回后  安全?\n");
    printf("  --------------------------  ----------  ----------  ------\n");
    printf("  return &local;              栈          被回收      ❌ 悬空\n");
    printf("  return local;               -           值被拷贝    ✅ 安全\n");
    printf("  static int v; return &v;    全局区      仍有效      ✅ static\n");
    printf("  调用者传地址进来写          调用者的栈  仍有效      ✅ 推荐\n");
    printf("  malloc 后返回               堆          free 前有效 ✅ 要 free\n");
    printf("\n  ★ 最关键的对比：\n");
    printf("     return local;   返回【值】-> 拷贝一份带走，安全\n");
    printf("     return &local;  返回【地址】-> 把门牌号给你，但房子拆了\n");

    /* ---------- 6. 一句话总结 ---------- */
    printf("\n############################################################\n");
    printf("#  一句话总结                                               #\n");
    printf("############################################################\n\n");
    printf("  局部变量的寿命 = 函数的执行期间。\n");
    printf("  函数一返回，它就不存在了 —— 此时任何指向它的地址都是悬空指针。\n\n");
    printf("  判断方法很简单：看地址开头\n");
    printf("     0x62xxxx  ->  栈   ->  出了函数就无效，别把地址给出去\n");
    printf("     0x40xxxx  ->  全局区 ->  全程有效（static、字面量）\n");

    return 0;
}
