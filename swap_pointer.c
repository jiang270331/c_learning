/* ============================================================
   swap_pointer.c —— 为什么 f(int *p, int *q) 里交换指针没用

   你在练习网站答「2 1」，正确答案「1 2」。
   这题跟你早做过的 swap_wrong 是同一个陷阱，只是换了层皮。

   三种写法逐一对跑：
     写法 1（题目里的）：交换【形参指针副本】—— 外面毫无变化
     写法 2（正确）：    交换【指针指向的值】 —— 这才换成功
     写法 3（进阶）：    交换【外面的指针变量本身】 —— 需要二级指针
   ============================================================ */
#include <stdio.h>
#include "utf8_console.h"

/* ============================================================
   写法 1：题目里的 f()  —— 交换形参（指针副本）
   ============================================================ */
void f_wrong(int *p, int *q)
{
    int *t = p;      /* t 记住 p 这个【副本】 */
    p = q;           /* 改的是副本 */
    q = t;           /* 改的也是副本 */
    /* 函数一结束，p、q 这两个副本就没了。
       外面 pa、pb 一个字都没动。 */
}

/* ============================================================
   写法 2：交换指针【指向的值】 —— 这才叫真的交换
   ============================================================ */
void f_swap_values(int *p, int *q)
{
    int t = *p;      /* 注意：是 *p，取出格子里的数 */
    *p = *q;
    *q = t;
}

/* ============================================================
   写法 3：交换【外面的指针变量本身】 —— 需要二级指针
   因为要让函数改到外面的 pa、pb，就得传它们的地址（int **）
   ============================================================ */
void f_swap_pointers(int **pp, int **pq)
{
    int *t = *pp;    /* 取出 pa 这个指针 */
    *pp = *pq;       /* 写回 pa 的格子 */
    *pq = t;         /* 写回 pb 的格子 */
}

int main(void)
{
    enable_utf8_console();

    printf("############################################################\n");
    printf("#   f(int *p, int *q) 里交换指针，到底发生了什么            #\n");
    printf("############################################################\n\n");

    /* ---------- 写法 1：题目 ---------- */
    printf("============================================================\n");
    printf("写法 1（题目里的）：交换形参副本  —— ❌ 没用\n");
    printf("============================================================\n\n");
    {
        int x = 1, y = 2;
        int *px = &x, *py = &y;

        printf("  初始：x=%d y=%d   px->x  py->y\n", x, y);
        printf("        px = %p   py = %p\n", (void *)px, (void *)py);

        f_wrong(px, py);

        printf("\n  调用 f_wrong(px, py) 之后：\n");
        printf("        x=%d y=%d   （值完全没变）\n", x, y);
        printf("        px = %p   py = %p\n", (void *)px, (void *)py);
        printf("  输出: %d %d     <- 正确答案就是 1 2\n\n", *px, *py);

        printf("  ⚠️ 为什么没用：\n");
        printf("     f() 收到的 p、q 是 px、py 的【副本】\n");
        printf("     f() 里 p = q 只改了副本，px、py 本身没动\n");
        printf("     函数一返回，副本就消失了\n");
        printf("     => 完全等价于你早做过的 swap_wrong\n");
    }

    /* ---------- 写法 2 ---------- */
    printf("\n============================================================\n");
    printf("写法 2：交换指针【指向的值】 —— ✅ 这才对\n");
    printf("============================================================\n\n");
    {
        int x = 1, y = 2;
        int *px = &x, *py = &y;

        printf("  初始：x=%d y=%d\n", x, y);
        f_swap_values(px, py);
        printf("  调用 f_swap_values(px, py) 之后：\n");
        printf("        x=%d y=%d   （值换了！）\n", x, y);
        printf("        px 还是指向 x，py 还是指向 y（指针没动）\n");
        printf("  输出: %d %d\n\n", *px, *py);

        printf("  ✅ 关键差别：换的是 *p 和 *q（格子里的【数】），\n");
        printf("     不是 p 和 q（指针本身）\n");
    }

    /* ---------- 写法 3 ---------- */
    printf("\n============================================================\n");
    printf("写法 3：交换【外面的指针变量本身】 —— 需要 int **\n");
    printf("============================================================\n\n");
    {
        int x = 1, y = 2;
        int *px = &x, *py = &y;

        printf("  初始：px->x  py->y\n");
        printf("        px = %p   py = %p\n", (void *)px, (void *)py);

        f_swap_pointers(&px, &py);       /* 注意：传的是 px、py 的地址 */

        printf("\n  调用 f_swap_pointers(&px, &py) 之后：\n");
        printf("        px = %p   py = %p\n", (void *)px, (void *)py);
        printf("        px 现在指向 %s，py 现在指向 %s\n",
               (px == &x) ? "x" : "y", (py == &x) ? "x" : "y");
        printf("        x=%d y=%d   （值没变，变的是指针指向）\n", x, y);
        printf("  输出: %d %d     <- 注意！这里输出变成 2 1 了\n\n", *px, *py);

        printf("  为什么：px、py 真的被交换了，\n");
        printf("          所以 *px 现在取的是 y 的值（2），*py 取 x 的值（1）\n");
    }

    /* ---------- 对照表 ---------- */
    printf("############################################################\n");
    printf("#  三种写法对照                                             #\n");
    printf("############################################################\n\n");
    printf("  写法                          函数签名              外面变了吗\n");
    printf("  ----------------------------  ------------------  ------------------\n");
    printf("  交换形参副本（题目里的）        f(int *p, int *q)   什么都没变     1 2\n");
    printf("  交换指向的值                    f(int *p, int *q)   值换了         2 1\n");
    printf("  交换外面的指针本身              f(int **p,int **q)  指向换了       2 1\n");
    printf("\n  ⚠️ 注意后两种都能输出 2 1，但机制完全不同：\n");
    printf("     写法 2 换的是【a、b 里的数】     （a 变 2，b 变 1）\n");
    printf("     写法 3 换的是【pa、pb 指向谁】   （a、b 没动，指针互换了）\n");

    printf("\n############################################################\n");
    printf("#  一句话总结                                               #\n");
    printf("############################################################\n\n");
    printf("  想改什么，就传【什么的地址】：\n\n");
    printf("     想改 int    ->  传 int *     ->  函数里写 *p = ...\n");
    printf("     想改 int *  ->  传 int **    ->  函数里写 **p = ...\n\n");
    printf("  题目里 f(int *p, int *q) 只能改到【外面的 int】，\n");
    printf("  改不到【外面的 int *】—— 因为它拿到的是指针的副本。\n\n");
    printf("  这跟 7.4 讲义里那条一模一样：\n");
    printf("     「形参是实参的复印件，改复印件不影响原件」\n");
    printf("     —— 不管这个「件」是 int 还是 int *\n");

    return 0;
}
