/* ============================================================
   ptr_assign.c —— 你练习网站上那道题（Grok 讲解的验证版）

   题目代码：
       int x = 5, y = 8;
       int *p = &x, *q = &y;
       printf("%d %d\n", *p, *q);     // 第 1 行
       *p = *q;
       printf("%d %d\n", x, y);       // 第 2 行
       p = q;
       *p = 1;
       printf("%d %d\n", x, y);       // 第 3 行

   你答的第三行是 1 1，正确答案是 8 1。
   这个程序把每一步的中间状态都打出来，看清到底发生了什么。
   ============================================================ */
#include <stdio.h>
#include "utf8_console.h"

/* 把 x、y 的真实地址一起传进来 —— 不能在函数里写 &x，
   因为那取到的是【形参 x】的地址，不是 main 里 x 的地址 */
static void show_state(const char *step, int x, int y,
                       int *p, int *q, const int *addr_x, const int *addr_y)
{
    const char *pn = "别处";
    const char *qn = "别处";
    if (p == addr_x) pn = "x";
    else if (p == addr_y) pn = "y";
    if (q == addr_x) qn = "x";
    else if (q == addr_y) qn = "y";

    printf("  [%s]\n", step);
    printf("      x = %d   y = %d\n", x, y);
    printf("      p 指向 %s (地址 %p)\n", pn, (void *)p);
    printf("      q 指向 %s (地址 %p)\n", qn, (void *)q);
    printf("      *p = %d   *q = %d\n\n", *p, *q);
}

int main(void)
{
    enable_utf8_console();

    int x = 5, y = 8;
    int *p = &x, *q = &y;

    printf("############################################################\n");
    printf("#   指针练习网站那道题：逐步看清每一步发生了什么            #\n");
    printf("############################################################\n\n");

    printf("初始：int x = 5, y = 8;  int *p = &x, *q = &y;\n\n");
    show_state("初始状态", x, y, p, q, &x, &y);

    printf("------------------------------------------------------------\n");
    printf("第 1 步：printf(\"%%d %%d\\n\", *p, *q);\n");
    printf("------------------------------------------------------------\n");
    printf("  输出: %d %d          <- 第 1 行（你答对了）\n", *p, *q);
    printf("  原理: *p 是 x 的值, *q 是 y 的值\n\n");

    printf("------------------------------------------------------------\n");
    printf("第 2 步：*p = *q;      ← 复制的是【值】\n");
    printf("------------------------------------------------------------\n");
    printf("  执行前: *p = %d（x）, *q = %d（y）\n", *p, *q);
    *p = *q;
    printf("  执行后: x = %d, y = %d\n", x, y);
    show_state("执行 *p = *q 之后", x, y, p, q, &x, &y);
    printf("  ⚠️ 关键: p 还是指向 x！只是把 x 的值改成了 y 的值\n");
    printf("     所以：x 和 y 都变成 8，但 p 指向没变\n");
    printf("  输出: %d %d          <- 第 2 行（你也答对了）\n\n", x, y);

    printf("------------------------------------------------------------\n");
    printf("第 3 步：p = q;        ← 复制的是【地址】\n");
    printf("------------------------------------------------------------\n");
    printf("  执行前: p 指向 %s\n", (p == &x) ? "x" : "y");
    p = q;
    printf("  执行后: p 指向 %s    <- p 被挪走了！\n", (p == &x) ? "x" : "y");
    show_state("执行 p = q 之后", x, y, p, q, &x, &y);
    printf("  ⚠️ 关键: x 和 y 的值【一个都没变】，变的只是 p 指向\n");
    printf("     现在 p 和 q 都指向 y\n\n");

    printf("------------------------------------------------------------\n");
    printf("第 4 步：*p = 1;       ← 现在改的是 y，不是 x！\n");
    printf("------------------------------------------------------------\n");
    printf("  执行前: *p = %d（因为 p 现在指向 y）\n", *p);
    *p = 1;
    printf("  执行后: x = %d, y = %d\n", x, y);
    show_state("执行 *p = 1 之后", x, y, p, q, &x, &y);
    printf("  输出: %d %d          <- 第 3 行（你答 1 1，正确是 %d %d）\n\n",
           x, y, x, y);

    printf("############################################################\n");
    printf("#  正确答案                                                 #\n");
    printf("############################################################\n\n");
    printf("  5 8          <- 第 1 行: *p 和 *q\n");
    printf("  8 8          <- 第 2 行: *p = *q 之后（两个都变 8）\n");
    printf("  8 1          <- 第 3 行: p = q 然后 *p = 1（只改了 y）\n\n");

    printf("  你答的是 1 1，错在最后一步 —— 以为改的还是 x。\n\n");

    printf("############################################################\n");
    printf("#  两道题的差别（背下来）                                   #\n");
    printf("############################################################\n\n");
    printf("  *p = *q    复制的是【格子里的数】\n");
    printf("             -> x 变成 y 的值, 但 p 仍然指向 x\n");
    printf("             -> 两个变量的值都变了\n\n");
    printf("  p = q      复制的是【地址】\n");
    printf("             -> p 改去指向 y, x 和 y 里的数都不变\n");
    printf("             -> 之后 *p 操作的就是 y 了\n\n");

    printf("  一句话记法:\n");
    printf("     带星号的等号（*p = *q）改【值】\n");
    printf("     不带星号的等号（p  = q ）改【指向】\n\n");

    printf("  这跟我们 7.3 讲义里那条一模一样:\n");
    printf("     p  <-> 地址      *p <-> 值      &p <-> p 自己的地址\n");

    return 0;
}
